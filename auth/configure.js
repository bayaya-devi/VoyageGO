import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const envPath = new URL('../.env.local', import.meta.url);
const outputPath = new URL('./runtime-config.js', import.meta.url);
const values = {};

try {
  const source = await readFile(envPath, 'utf8');
  for (const line of source.split(/\r?\n/)) {
    const match = line.match(/^\s*(SUPABASE_URL|SUPABASE_PUBLISHABLE_KEY)\s*=\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^(?:"([\s\S]*)"|'([\s\S]*)')$/, (_all, doubleQuoted, singleQuoted) => doubleQuoted ?? singleQuoted);
  }
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const supabaseUrl = process.env.SUPABASE_URL || values.SUPABASE_URL || '';
const supabasePublishableKey = process.env.SUPABASE_PUBLISHABLE_KEY || values.SUPABASE_PUBLISHABLE_KEY || '';
let normalizedUrl = '';

if (supabaseUrl || supabasePublishableKey) {
  let parsed;
  try { parsed = new URL(supabaseUrl); } catch { throw new Error('SUPABASE_URL must be a valid HTTPS URL (HTTP is allowed only on localhost).'); }
  const local = ['localhost', '127.0.0.1', '::1'].includes(parsed.hostname);
  if (!['https:', ...(local ? ['http:'] : [])].includes(parsed.protocol) || parsed.username || parsed.password || parsed.search || parsed.hash || parsed.pathname !== '/') {
    throw new Error('SUPABASE_URL must be a trusted HTTPS project origin (or local Supabase URL).');
  }
  if (!supabasePublishableKey || /service[_-]?role/i.test(supabasePublishableKey)) {
    throw new Error('Set SUPABASE_PUBLISHABLE_KEY to a publishable/anon key. Privileged service_role keys are forbidden.');
  }
  normalizedUrl = parsed.origin;
}

const contents = `// Generated by npm run configure:auth. Contains public browser settings only.\nexport const authConfig = Object.freeze(${JSON.stringify({ supabaseUrl: normalizedUrl, supabasePublishableKey }, null, 2)});\n`;
await writeFile(outputPath, contents, 'utf8');
console.log(normalizedUrl ? `Public Supabase settings written to ${fileURLToPath(outputPath)}.` : 'Authentication remains disabled: add SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY to .env.local.');
